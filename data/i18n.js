export const localeCodes = supportedLocales.map((locale) => locale.code);

export function getDictionary(code = "en") {
  return dictionaries[code] || dictionaries.en;
}

export function getLocaleInfo(code = "en") {
  return supportedLocales.find((locale) => locale.code === code) || supportedLocales[0];
}

export function localePath(code = "en") {
  return code === "en" ? "/" : `/${code}/`;
}

export const languageAlternates = Object.fromEntries(
  supportedLocales.map((locale) => [locale.code, localePath(locale.code)])
);
languageAlternates["x-default"] = "/";
